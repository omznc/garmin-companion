//! The TypeScript contract of the bridge.
//!
//! `garmin_api::commands::COMMANDS` lists the commands of the API crate. This
//! module lists the commands that only the bridge runs, and writes the
//! generated `commands.ts` with both lists. Run `scripts/gen-types.sh` to write it.

use garmin_api::commands::{Command, COMMANDS};

const fn cmd(name: &'static str, args: &'static str, result: &'static str) -> Command {
    Command { name, args, result }
}

/// The commands that `garmin-ffi` runs itself: events, the coach and its saved threads.
pub(crate) const FFI_COMMANDS: &[Command] = &[
    cmd("sync", "SyncArgs | undefined", "SyncSummary"),
    cmd("ask_send", "SendArgs", "Empty"),
    cmd("ask_stop", "undefined", "Empty"),
    cmd("ask_config", "undefined", "ChatConfig"),
    cmd("ask_save_config", "SaveConfigArgs", "Empty"),
    cmd("chat_list", "ListArgs | undefined", "ThreadList"),
    cmd("chat_get", "SessionArgs", "Thread | null"),
    cmd("chat_rename", "RenameArgs", "Empty"),
    cmd("chat_delete", "SessionArgs", "Empty"),
    cmd(
        "cloud_account",
        "CloudAccountArgs | undefined",
        "AccountView | null",
    ),
    cmd("cloud_send_code", "CloudEmailArgs", "Empty"),
    cmd("cloud_verify", "CloudVerifyArgs", "CloudVerified"),
    cmd("cloud_sign_out", "undefined", "Empty"),
    cmd("workout_create", "WorkoutCreateArgs", "WorkoutCreated"),
];

/// The events of `subscribe`, by kind: the payload types.
const EVENTS: &[(&str, &str)] = &[
    // `ask.rs` adds the session and the turn to the JSON of the event.
    ("ask", "AskEvent & { sessionId: string; turnId: string }"),
    ("sync-progress", "SyncEvent"),
];

/// The type names that a type expression uses.
fn type_names(expr: &str) -> Vec<&str> {
    expr.split(|c: char| !c.is_alphanumeric())
        .filter(|w| w.starts_with(|c: char| c.is_uppercase()))
        .filter(|w| !matches!(*w, "Array" | "Record" | "Empty"))
        .collect()
}

/// The text of `generated/commands.ts`.
fn commands_file() -> String {
    let all: Vec<Command> = COMMANDS.iter().chain(FFI_COMMANDS).copied().collect();
    let mut names: Vec<&str> = all
        .iter()
        .flat_map(|c| type_names(c.args).into_iter().chain(type_names(c.result)))
        .chain(EVENTS.iter().flat_map(|(_, t)| type_names(t)))
        .collect();
    names.sort_unstable();
    names.dedup();
    let mut out = String::from(
        "// This file is generated by scripts/gen-types.sh. Do not edit it.\n\
         // The source is garmin_api::commands::COMMANDS and garmin-ffi/src/contract.rs.\n",
    );
    for name in names {
        out.push_str(&format!("import type {{ {name} }} from \"./{name}\";\n"));
    }
    out.push_str("\n/** The result of a command that returns `{}`. */\n");
    out.push_str("export type Empty = Record<string, never>;\n\n");
    out.push_str(&garmin_api::commands::commands_type(&all));
    out.push_str("\n/** The events of `subscribe`, by kind. */\nexport type Events = {\n");
    for (kind, payload) in EVENTS {
        out.push_str(&format!("  \"{kind}\": {payload};\n"));
    }
    out.push_str("};\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn no_command_is_listed_twice() {
        let all: HashSet<_> = COMMANDS
            .iter()
            .chain(FFI_COMMANDS)
            .map(|c| c.name)
            .collect();
        assert_eq!(all.len(), COMMANDS.len() + FFI_COMMANDS.len());
    }

    #[tokio::test]
    async fn every_bridge_command_has_a_handler() {
        // `ask_stop` ends the turn of a parallel test, so this test takes the lock.
        let _seq = crate::TEST_LOCK.lock().await;
        let none = serde_json::json!({});
        for c in FFI_COMMANDS.iter().filter(|c| c.name != "sync") {
            let handled = crate::ask::handle(c.name, &none, true).await.is_some()
                || crate::chat::handle(c.name, &none, true).is_some()
                || crate::cloud::handle(c.name, &none, true).await.is_some()
                || crate::workout::handle(c.name, &none, true).await.is_some();
            assert!(handled, "{} has no handler", c.name);
        }
    }

    /// Two Rust types with one TypeScript name write the same file, and the last
    /// one wins without a warning. Give one of them `ts(rename = "...")`.
    #[test]
    fn no_two_exported_types_share_a_name() {
        let crates = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let mut seen: Vec<String> = Vec::new();
        for krate in std::fs::read_dir(crates).unwrap() {
            let src = krate.unwrap().path().join("src");
            for file in rust_files(&src) {
                if file.ends_with("contract.rs") {
                    continue;
                }
                let text = std::fs::read_to_string(file).unwrap();
                let lines: Vec<&str> = text.lines().collect();
                for (i, line) in lines.iter().enumerate() {
                    if line.contains("derive(ts_rs::TS") || line.trim() == "derive(ts_rs::TS)," {
                        seen.push(ts_name_after(&lines[i..]));
                    }
                }
            }
        }
        let mut sorted = seen.clone();
        sorted.sort();
        let dups: Vec<_> = sorted.windows(2).filter(|w| w[0] == w[1]).collect();
        assert!(
            seen.len() > 100 && dups.is_empty(),
            "same name twice: {dups:?}"
        );
    }

    fn rust_files(dir: &std::path::Path) -> Vec<std::path::PathBuf> {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return Vec::new();
        };
        entries
            .flat_map(|e| {
                let path = e.unwrap().path();
                if path.is_dir() {
                    rust_files(&path)
                } else if path.extension().is_some_and(|x| x == "rs") {
                    vec![path]
                } else {
                    Vec::new()
                }
            })
            .collect()
    }

    /// The TypeScript name of the item after a derive line: a `rename`, or the Rust name.
    fn ts_name_after(from: &[&str]) -> String {
        let mut rename = None;
        for line in from.iter().take(10) {
            if let Some(rest) = line.split("rename = \"").nth(1) {
                rename = rest.split('"').next().map(str::to_owned);
            }
            let words: Vec<&str> = line.split_whitespace().collect();
            let at = words.iter().position(|w| matches!(*w, "struct" | "enum"));
            if let Some(name) = at.and_then(|i| words.get(i + 1)) {
                let name = name.trim_end_matches(['{', '(', ';']);
                return rename.unwrap_or_else(|| name.to_owned());
            }
        }
        panic!("no item after a derive: {from:?}");
    }

    #[test]
    fn the_file_imports_each_type_once() {
        let text = commands_file();
        assert!(text.contains("import type { TodayView } from \"./TodayView\";"));
        assert_eq!(text.matches("import type { Thread }").count(), 1);
        assert!(text.contains("\"sync-progress\": SyncEvent;"));
    }

    /// Writes `commands.ts` next to the files of ts-rs. The name starts with
    /// `export_bindings`, so one test filter runs all the writers.
    #[cfg(feature = "ts-rs")]
    #[test]
    fn export_bindings_commands() {
        let dir = std::env::var("TS_RS_EXPORT_DIR").expect("TS_RS_EXPORT_DIR is not set");
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            std::path::Path::new(&dir).join("commands.ts"),
            commands_file(),
        )
        .unwrap();
    }
}

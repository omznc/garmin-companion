// `REQUEST_INSTALL_PACKAGES` is what lets the sideloaded APK update itself
// (see AndroidManifest.xml), and it is on Google Play's restricted list — only
// app stores may declare it. The `.aab` exists for Play and the `.apk` does
// not, so the permission has to be in one and not the other.
//
// It can't be a flavour or a build type, which would be the obvious answer:
// both artifacts come out of the *same* variant, and adding a dimension to
// split them would multiply the per-ABI Rust compile by two — the expensive
// half of an Android build here, four times over.
//
// So the merged manifest is edited on the way past instead, and only when
// `-PplayBundle` is set. CI passes it as `ORG_GRADLE_PROJECT_playBundle` on the
// second of its two builds; nothing else does, so a local build and the
// released APK both keep the permission.
//
// NOTE: this file is regenerated by `tauri android init`. If you re-run it,
// this block and the class below come back out.
androidComponents {
    onVariants { variant ->
        if (!project.hasProperty("playBundle")) return@onVariants

        val strip = tasks.register(
            "strip${variant.name.replaceFirstChar(Char::titlecase)}InstallPermission",
            StripInstallPermission::class.java,
        )
        variant.artifacts
            .use(strip)
            .wiredWithFiles(
                StripInstallPermission::mergedManifest,
                StripInstallPermission::strippedManifest,
            )
            .toTransform(SingleArtifact.MERGED_MANIFEST)
    }
}

abstract class StripInstallPermission : DefaultTask() {
    @get:InputFile
    abstract val mergedManifest: RegularFileProperty

    @get:OutputFile
    abstract val strippedManifest: RegularFileProperty

    @TaskAction
    fun strip() {
        val merged = mergedManifest.get().asFile.readText()
        val stripped = merged.replace(PERMISSION, "")
        // Loud on purpose. A rename or a reformat upstream would turn this into
        // a no-op, and the failure it hides is the worst kind: a bundle that
        // uploads fine and gets rejected by Play review weeks later, or worse,
        // isn't. Nothing about the artifact would look wrong in the meantime.
        if (stripped == merged) {
            throw GradleException(
                "playBundle is set but REQUEST_INSTALL_PACKAGES wasn't found in the merged " +
                    "manifest — the pattern in StripInstallPermission no longer matches.",
            )
        }
        strippedManifest.get().asFile.writeText(stripped)
    }

    private companion object {
        val PERMISSION = Regex(
            """\s*<uses-permission[^>]*android:name="android\.permission\.REQUEST_INSTALL_PACKAGES"[^>]*/>""",
        )
    }
}


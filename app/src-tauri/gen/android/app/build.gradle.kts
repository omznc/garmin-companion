// Release signing. `keystore.properties` is gitignored and is written by CI
// from repository secrets — see `.github/workflows/release.yml`, and RELEASING
// for how to generate the keystore.
//
// Absent is a supported state, not a broken one: a debug build signs itself
// with the local debug key and needs none of this, and requiring the file would
// mean nobody could build the project without first being handed the signing
// key. When it is missing, `signingConfigs` below simply isn't created and a
// release build comes out unsigned — which fails to install, loudly, rather
// than shipping something signed by the wrong key.
//
// NOTE: this file is regenerated by `tauri android init`. If you re-run it,
// this block and the `signingConfig` line in `buildTypes` come back out.
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}
val hasKeystore = keystorePropertiesFile.exists()

